        // Tri insensible aux accents (É trié avec E, etc.) pour un ordre français correct.
        $fold = static fn (string $s): string => strtr(
            mb_strtolower($s),
            ['à' => 'a', 'â' => 'a', 'ä' => 'a', 'ç' => 'c', 'é' => 'e', 'è' => 'e',
                'ê' => 'e', 'ë' => 'e', 'î' => 'i', 'ï' => 'i', 'ô' => 'o', 'ö' => 'o',
                'û' => 'u', 'ü' => 'u', 'ù' => 'u']
        );
        usort($out, static fn ($a, $b) => $fold($a['name']) <=> $fold($b['name']));

        return $out;
    }

    /** Indicatif d'un code ISO, ou null. */
    public static function dialFor(string $iso): ?string
    {
        return self::LIST[strtolower($iso)]['dial'] ?? null;
    }
